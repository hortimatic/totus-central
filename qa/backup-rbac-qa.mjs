check(/\['admin','gerente','encargado'\]/.test(rbac),'Encargado está en supervisión operativa');
check(/\['admin','gerente'\]/.test(rbac),'Gerente está en gestión operativa');
check(/\['incidents','Incidencias'\]/.test(rbac)&&/\['documents','Documentación'\]/.test(rbac),'Navegación supervisora incluye expediente nuevo');
check(/employee_incidents/.test(records)&&/employee_incident_audit_log/.test(records),'Frontend carga incidencias y auditoría');
check(/employee_documents/.test(records)&&/employee_document_audit_log/.test(records),'Frontend carga documentación y auditoría');
check(/employee-documents/.test(records),'Frontend usa bucket documental dedicado');
check(/archiveEmployeeDocument/.test(records)&&/restoreEmployeeDocument/.test(records),'Documentos se archivan/reactivan sin borrado funcional');
check(!/\.delete\(/.test(records),'Expediente no borra registros de negocio desde frontend');
if(fail.length){console.error('BACKUP/RBAC/EXPEDIENTE QA FALLIDA');fail.forEach(x=>console.error('✗ '+x));process.exit(1)}
console.log(`BACKUP/RBAC/EXPEDIENTE QA OK · ${ok.length}`);ok.forEach(x=>console.log('✓ '+x));