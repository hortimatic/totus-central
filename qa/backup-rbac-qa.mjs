check(/V3_TABLES/.test(backup)&&/V4_TABLES/.test(backup),'Backup separa esquemas V3 y V4');
check(/employee_incidents/.test(backup)&&/employee_documents/.test(backup),'Backup V4 incluye incidencias y documentación de empleado');
check(/employee-documents/.test(backup),'Backup V4 incluye bucket documental privado');
check(/\[1,2,3,4\]/.test(backup),'Validador mantiene compatibilidad V1/V2/V3/V4');
check(/admin_rebuild_member_locations_legacy/.test(backup),'Backups V1/V2 reconstruyen asignaciones heredadas');
check(/admin_validate_backup_auth/.test(backup),'Rollback exacto mantiene preflight de Auth');
check(/createSafetyBackup/.test(backup),'Rollback/restauración crea copia previa');
check(/verifyRestoredBackup/.test(backup),'Rollback/restauración verifica integridad');
check(/user-avatars/.test(team),'Copia histórica mantiene avatares');
check(/task-evidence/.test(team)&&/internal-library/.test(team),'Copia histórica mantiene evidencias y biblioteca');
check(/totus-rbac\.js/.test(index),'Shell carga RBAC');
check(/totus-employee-records\.js/.test(index),'Shell carga expediente de empleado');
check(/canManageTeam/.test(rbac)&&/canSuperviseTeam/.test(rbac),'RBAC separa gerencia y supervisión');
